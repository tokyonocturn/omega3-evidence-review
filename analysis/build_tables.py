#!/usr/bin/env python3
"""Validate the omega-3 datasets and regenerate every Markdown table.

The datasets in ../data are the single source of truth. Nothing in
docs/generated/ or docs/references.md is edited by hand: this script rebuilds
them, and `--check` fails when the committed files are stale or a relative link
does not resolve.

Usage:
    python analysis/build_tables.py            # validate + regenerate
    python analysis/build_tables.py --check    # fail if outputs are stale
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
DOCS = ROOT / "docs"
GENERATED = DOCS / "generated"

GENERATED_NOTE = (
    "<!-- Generated by analysis/build_tables.py from data/*.csv. Do not edit. -->\n"
)

CATEGORIES = {"Fish oil concentrate", "Cod liver oil", "Krill oil", "Algal oil"}
FORMS = {"TG", "rTG", "EE", "Phospholipid", "Algal", "Unstated"}
DOMAINS = {
    "Cardiovascular",
    "Lipids",
    "Neurology",
    "Mental health",
    "Musculoskeletal",
    "Ophthalmology",
    "Obstetrics",
    "Oncology",
    "Other",
    "Safety",
}
STATUSES = {"Benefit", "No benefit", "Harm", "Mixed", "Insufficient", "Established"}
CERTAINTIES = {"High", "Moderate", "Low", "Very low", "Not graded"}
VERDICTS = {
    "Supported",
    "Partially supported",
    "Unsupported",
    "False",
    "Misleading",
}

PRODUCT_COLUMNS = [
    "id", "brand", "product", "category", "form", "source", "serving_softgels",
    "servings_per_container", "oil_mg", "epa_mg", "dha_mg", "other_omega3_mg",
    "certification", "added_vitamins", "price_usd", "price_date", "price_channel",
    "price_url", "label_url", "assay_status", "notes",
]
EVIDENCE_COLUMNS = [
    "id", "domain", "question", "population", "design", "n", "dose_mg",
    "duration", "metric", "estimate", "ci_low", "ci_high", "status",
    "certainty", "reference_id", "notes",
]
CLAIM_COLUMNS = ["id", "claim", "verdict", "explanation", "evidence_ids", "reference_ids"]
DOSING_COLUMNS = [
    "purpose", "target_low_mg", "target_high_mg", "basis", "notes", "reference_ids",
]
STANDARD_COLUMNS = [
    "id", "parameter", "limit_value", "unit", "applies_to", "source_id", "notes",
]
SURVEY_COLUMNS = [
    "id", "study", "market", "year_sampled", "n_products", "parameter", "result",
    "unit", "source_id", "notes",
]
REFERENCE_COLUMNS = ["id", "citation", "type", "doi", "pmid", "url"]

errors: list[str] = []


def fail(message: str) -> None:
    errors.append(message)


def load(name: str, required: list[str]) -> list[dict[str, str]]:
    path = DATA / name
    if not path.exists():
        fail(f"{name}: file is missing")
        return []
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        fieldnames = reader.fieldnames or []
        missing = [column for column in required if column not in fieldnames]
        if missing:
            fail(f"{name}: missing columns {missing}")
            return []
        rows = []
        for row in reader:
            if None in row:
                fail(f"{name}: row {reader.line_num} has more fields than the header (unquoted comma?)")
                continue
            rows.append({key: (value or "").strip() for key, value in row.items()})
    if not rows:
        fail(f"{name}: contains no rows")
    return rows


def number(row: dict[str, str], field: str, *, allow_blank: bool = True) -> float | None:
    raw = row.get(field, "")
    if raw == "":
        if allow_blank:
            return None
        fail(f"{row.get('id', '?')}: '{field}' must not be blank")
        return None
    try:
        return float(raw.replace(",", ""))
    except ValueError:
        fail(f"{row.get('id', '?')}: '{field}' is not numeric: {raw!r}")
        return None


def require_enum(row: dict[str, str], field: str, allowed: set[str], source: str) -> None:
    value = row.get(field, "")
    if value not in allowed:
        fail(f"{source}: {row.get('id', '?')}: {field}={value!r} not in {sorted(allowed)}")


def split_refs(raw: str) -> list[str]:
    return [token.strip() for token in re.split(r"[;,]", raw) if token.strip()]


def fmt_money(value: float) -> str:
    return f"${value:,.2f}"


def fmt_number(value: float, digits: int = 2) -> str:
    text = f"{value:,.{digits}f}"
    if "." in text:
        text = text.rstrip("0").rstrip(".")
    return text


# --------------------------------------------------------------------------- #
# Derived product metrics
# --------------------------------------------------------------------------- #

def product_metrics(row: dict[str, str]) -> dict[str, float | None]:
    epa = number(row, "epa_mg", allow_blank=False) or 0.0
    dha = number(row, "dha_mg", allow_blank=False) or 0.0
    servings = number(row, "servings_per_container", allow_blank=False) or 0.0
    price = number(row, "price_usd", allow_blank=False) or 0.0
    oil = number(row, "oil_mg")
    per_serving = (epa + dha) / 1000.0
    total = per_serving * servings
    cost_per_gram = price / total if total > 0 else None
    concentration = ((epa + dha) / oil * 100.0) if oil and oil > 0 else None
    return {
        "epa": epa,
        "dha": dha,
        "per_serving_mg": epa + dha,
        "per_serving_g": per_serving,
        "total_g": total,
        "price": price,
        "cost_per_gram": cost_per_gram,
        "concentration": concentration,
        "cost_per_30d": cost_per_gram * 30 if cost_per_gram else None,
        "cost_per_year_2g": cost_per_gram * 730 if cost_per_gram else None,
    }


def value_tier(cost_per_gram: float) -> str:
    if cost_per_gram < 0.40:
        return "Excellent"
    if cost_per_gram < 0.70:
        return "Good"
    if cost_per_gram < 1.20:
        return "Fair"
    if cost_per_gram < 2.00:
        return "Poor"
    return "Very poor"


# --------------------------------------------------------------------------- #
# Validation
# --------------------------------------------------------------------------- #

def validate() -> dict[str, list[dict[str, str]]]:
    products = load("products.csv", PRODUCT_COLUMNS)
    evidence = load("evidence.csv", EVIDENCE_COLUMNS)
    claims = load("claims.csv", CLAIM_COLUMNS)
    dosing = load("dosing.csv", DOSING_COLUMNS)
    standards = load("quality_standards.csv", STANDARD_COLUMNS)
    surveys = load("quality_surveys.csv", SURVEY_COLUMNS)
    references = load("references.csv", REFERENCE_COLUMNS)

    ref_ids = {row["id"] for row in references}
    if len(ref_ids) != len(references):
        fail("references.csv: duplicate IDs")
    for row in references:
        if not (row["doi"] or row["pmid"] or row["url"]):
            fail(f"references.csv: {row['id']} has no DOI, PMID or URL")

    seen: set[str] = set()
    for row in products:
        if row["id"] in seen:
            fail(f"products.csv: duplicate ID {row['id']}")
        seen.add(row["id"])
        require_enum(row, "category", CATEGORIES, "products.csv")
        require_enum(row, "form", FORMS, "products.csv")
        try:
            date.fromisoformat(row["price_date"])
        except ValueError:
            fail(f"products.csv: {row['id']}: price_date is not ISO 8601")
        metrics = product_metrics(row)
        if (metrics["per_serving_mg"] or 0) <= 0:
            fail(f"products.csv: {row['id']}: EPA+DHA per serving must be positive")
        if (metrics["price"] or 0) <= 0:
            fail(f"products.csv: {row['id']}: price must be positive")
        servings = number(row, "servings_per_container")
        if servings is not None and not (0 < servings <= 500):
            fail(f"products.csv: {row['id']}: implausible servings_per_container")
        oil = number(row, "oil_mg")
        other = number(row, "other_omega3_mg") or 0.0
        if oil is not None and metrics["per_serving_mg"] + other > oil * 1.05:
            fail(
                f"products.csv: {row['id']}: EPA+DHA+other ({metrics['per_serving_mg'] + other:.0f} mg) "
                f"exceeds declared oil ({oil:.0f} mg)"
            )

    evidence_ids: set[str] = set()
    for row in evidence:
        if row["id"] in evidence_ids:
            fail(f"evidence.csv: duplicate ID {row['id']}")
        evidence_ids.add(row["id"])
        require_enum(row, "domain", DOMAINS, "evidence.csv")
        require_enum(row, "status", STATUSES, "evidence.csv")
        require_enum(row, "certainty", CERTAINTIES, "evidence.csv")
        for field in ("n", "estimate", "ci_low", "ci_high"):
            number(row, field)
        for ref in split_refs(row["reference_id"]):
            if ref not in ref_ids:
                fail(f"evidence.csv: {row['id']}: unknown reference {ref}")
        low, high = number(row, "ci_low"), number(row, "ci_high")
        if low is not None and high is not None and low > high:
            fail(f"evidence.csv: {row['id']}: ci_low > ci_high")

    claim_ids: set[str] = set()
    for row in claims:
        if row["id"] in claim_ids:
            fail(f"claims.csv: duplicate ID {row['id']}")
        claim_ids.add(row["id"])
        require_enum(row, "verdict", VERDICTS, "claims.csv")
        for ref in split_refs(row["reference_ids"]):
            if ref not in ref_ids:
                fail(f"claims.csv: {row['id']}: unknown reference {ref}")
        for item in split_refs(row["evidence_ids"]):
            if item not in evidence_ids:
                fail(f"claims.csv: {row['id']}: unknown evidence {item}")

    for row in dosing:
        low, high = number(row, "target_low_mg"), number(row, "target_high_mg")
        if low is not None and high is not None and low > high:
            fail(f"dosing.csv: {row['purpose']}: target_low > target_high")
        for ref in split_refs(row["reference_ids"]):
            if ref not in ref_ids:
                fail(f"dosing.csv: {row['purpose']}: unknown reference {ref}")

    for row in standards:
        for ref in split_refs(row["source_id"]):
            if ref.startswith("R") and ref not in ref_ids:
                fail(f"quality_standards.csv: {row['id']}: unknown reference {ref}")
    for row in surveys:
        for ref in split_refs(row["source_id"]):
            if ref.startswith("R") and ref not in ref_ids:
                fail(f"quality_surveys.csv: {row['id']}: unknown reference {ref}")

    if not (DOCS / "generated").exists():
        (DOCS / "generated").mkdir(parents=True, exist_ok=True)

    return {
        "products": products,
        "evidence": evidence,
        "claims": claims,
        "dosing": dosing,
        "standards": standards,
        "surveys": surveys,
        "references": references,
    }


