def render_brand_table(products: list[dict[str, str]]) -> str:
    rows = []
    for row in products:
        metrics = product_metrics(row)
        rows.append((metrics["cost_per_gram"] or 0.0, row, metrics))
    rows.sort(key=lambda item: item[0])

    lines = [GENERATED_NOTE, "# Brand and cost comparison", "",
             "Sorted by cost per gram of EPA+DHA. Every value is calculated from the",
             "labelled EPA and DHA in `data/products.csv`; total fish oil, total omega-3",
             "and DPA are excluded. Prices are one-time US retail snapshots dated",
             "2026-11-18 and will change.", "",
             "| Product | Category | Form | EPA+DHA per serving | EPA+DHA % of oil | Cost per g EPA+DHA | 30 days at 1 g/day | 1 year at 2 g/day | Tier | Certification |",
             "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- |"]

    for cost, row, metrics in rows:
        concentration = (
            f"{metrics['concentration']:.1f}%"
            if metrics["concentration"] is not None
            else "not declared"
        )
        label = f"**{row['brand']}** {row['product']}"
        if "Promotional" in row["price_channel"]:
            label += " (promo)"
        lines.append(
            "| {label} | {category} | {form} | {serving} mg | {conc} | {cost} | {month} | {year} | {tier} | {cert} |".format(
                label=label,
                category=row["category"],
                form=row["form"],
                serving=fmt_number(metrics["per_serving_mg"] or 0, 0),
                conc=concentration,
                cost=fmt_money(cost),
                month=fmt_money(metrics["cost_per_30d"] or 0),
                year=fmt_money(metrics["cost_per_year_2g"] or 0),
                tier=value_tier(cost),
                cert=row["certification"],
            )
        )

    cheapest = rows[0]
    dearest = rows[-1]
    fish = [r for r in rows if r[1]["category"] == "Fish oil concentrate"]
    krill = [r for r in rows if r[1]["category"] == "Krill oil"]
    algal = [r for r in rows if r[1]["category"] == "Algal oil"]
    cod = [r for r in rows if r[1]["category"] == "Cod liver oil"]

    def median(values: list[float]) -> float:
        ordered = sorted(values)
        middle = len(ordered) // 2
        if len(ordered) % 2:
            return ordered[middle]
        return (ordered[middle - 1] + ordered[middle]) / 2

    lines += [
        "",
        "## What the table shows",
        "",
        f"- **Cheapest per gram:** {cheapest[1]['brand']} {cheapest[1]['product']} at "
        f"{fmt_money(cheapest[0])}/g of EPA+DHA.",
        f"- **Most expensive per gram:** {dearest[1]['brand']} {dearest[1]['product']} at "
        f"{fmt_money(dearest[0])}/g, a {dearest[0] / cheapest[0]:.0f}-fold difference.",
        f"- **Median cost per gram:** fish oil concentrates {fmt_money(median([r[0] for r in fish]))}; "
        f"krill oil {fmt_money(median([r[0] for r in krill]))}; "
        f"algal oil {fmt_money(median([r[0] for r in algal]))}; "
        f"cod liver oil {fmt_money(median([r[0] for r in cod]))}.",
        "- Concentration, not price alone, separates value: the cheapest products deliver",
        "  750-2,070 mg of EPA+DHA per serving in one or two softgels, while several",
        "  premium-priced products deliver under 500 mg per serving.",
        "",
        "## Label transparency",
        "",
    ]

    undeclared_form = [r for r in products if r["form"] == "Unstated"]
    undeclared_oil = [r for r in products if not r["oil_mg"]]
    undeclared_species = [r for r in products if "not stated" in r["source"].lower()]
    lines += [
        f"- **{len(undeclared_form)} of {len(products)}** products do not declare their chemical form.",
        f"- **{len(undeclared_oil)} of {len(products)}** do not declare total oil or concentrate mass, so",
        "  EPA+DHA concentration cannot be calculated from the label.",
        f"- **{len(undeclared_species)} of {len(products)}** do not name the fish species.",
        "- Mass-market 1,000-1,200 mg fish oils that print only a combined omega-3 number",
        "  (or no split at all) cannot be scored here; they are listed in",
        "  [`docs/10-brands-cost.md`](../10-brands-cost.md).",
        "",
        "## Caveats",
        "",
        "- Prices exclude tax, shipping and subscriptions; promotional prices are marked.",
        "- Labelled content is not assayed content. Published market surveys have found",
        "  products containing well below their labelled EPA+DHA, so a cheap product that",
        "  underfills its label could be worse value than the table suggests.",
        "- A certification column entry describes the brand's programme, not a test of the",
        "  specific bottle purchased.",
        "",
    ]
    return "\n".join(lines)


def render_evidence(evidence: list[dict[str, str]]) -> str:
    grouped: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in evidence:
        grouped[row["domain"]].append(row)

    lines = [GENERATED_NOTE, "# Evidence tables", "",
             f"{len(evidence)} graded rows. Effect estimates are reported in the units used",
             "by the source; `No benefit` means the confidence interval is compatible with",
             "no effect, not that harm was shown.", ""]

    for domain in sorted(grouped):
        rows = sorted(grouped[domain], key=lambda row: row["id"])
        lines += [f"## {domain}", "",
                  "| ID | Question | Design | N | Dose (mg/day) | Effect (95% CI) | Certainty | Status |",
                  "| --- | --- | --- | ---: | ---: | --- | --- | --- |"]
        for row in rows:
            estimate = number(row, "estimate")
            low, high = number(row, "ci_low"), number(row, "ci_high")
            if estimate is None:
                effect = "see note"
            elif low is not None and high is not None:
                effect = f"{fmt_number(estimate, 3)} ({fmt_number(low, 3)} to {fmt_number(high, 3)})"
            else:
                effect = fmt_number(estimate, 3)
            effect = f"{effect} {row['metric']}".strip()
            lines.append(
                "| {id} | {question} | {design} | {n} | {dose} | {effect} | {certainty} | {status} |".format(
                    id=row["id"],
                    question=row["question"],
                    design=row["design"],
                    n=row["n"] or "-",
                    dose=row["dose_mg"] or "-",
                    effect=effect,
                    certainty=row["certainty"],
                    status=row["status"],
                )
            )
        lines.append("")

    lines += ["## Reading the certainty grades", "",
              "- **High:** further research is very unlikely to change the estimate.",
              "- **Moderate:** further research may change the estimate materially.",
              "- **Low:** further research is likely to change the estimate.",
              "- **Very low:** the estimate is uncertain and often based on few events.",
              "",
              "Certainty is not the same as effect size. A high-certainty null result is a",
              "strong finding, and a low-certainty large effect is a weak one.", ""]
    return "\n".join(lines)


def render_claims(claims: list[dict[str, str]]) -> str:
    order = ["Supported", "Partially supported", "Misleading", "Unsupported", "False"]
    counts = {verdict: sum(1 for row in claims if row["verdict"] == verdict) for verdict in order}

    lines = [GENERATED_NOTE, "# Claims adjudication", "",
             f"{len(claims)} claims circulating in marketing, journalism and clinical",
             "conversation, each checked against the evidence rows.", "",
             "| Verdict | Count |", "| --- | ---: |"]
    for verdict in order:
        lines.append(f"| {verdict} | {counts[verdict]} |")

    for verdict in order:
        rows = [row for row in claims if row["verdict"] == verdict]
        if not rows:
            continue
        lines += ["", f"## {verdict}", "",
                  "| ID | Claim | What the evidence shows | Evidence |",
                  "| --- | --- | --- | --- |"]
        for row in rows:
            lines.append(
                "| {id} | {claim} | {explanation} | {evidence} |".format(
                    id=row["id"],
                    claim=row["claim"].replace("|", "\\|"),
                    explanation=row["explanation"].replace("|", "\\|"),
                    evidence=row["evidence_ids"].replace(";", ", "),
                )
            )
    lines.append("")
    return "\n".join(lines)


def render_dosing(dosing: list[dict[str, str]]) -> str:
    lines = [GENERATED_NOTE, "# Dosage table", "",
             "EPA+DHA doses by purpose. These are evidence-derived targets, not",
             "prescriptions; the `0` row records that no supplement dose is justified by",
             "current trial evidence.", "",
             "| Purpose | EPA+DHA per day | Basis | What it does and does not do |",
             "| --- | ---: | --- | --- |"]
    for row in dosing:
        low, high = number(row, "target_low_mg"), number(row, "target_high_mg")
        if low == 0 and high == 0:
            dose = "none justified"
        elif low == high:
            dose = f"{fmt_number(low or 0, 0)} mg"
        else:
            dose = f"{fmt_number(low or 0, 0)}-{fmt_number(high or 0, 0)} mg"
        lines.append(
            "| {purpose} | {dose} | {basis} | {notes} |".format(
                purpose=row["purpose"],
                dose=dose,
                basis=row["basis"],
                notes=row["notes"].replace("|", "\\|"),
            )
        )
    lines.append("")
    return "\n".join(lines)


def render_standards(standards: list[dict[str, str]]) -> str:
    lines = [GENERATED_NOTE, "# Quality standards", "",
             "The limits a fish oil has to meet to be considered non-oxidised and",
             "contaminant-compliant. GOED and Codex limits are voluntary in most markets;",
             "the EU contaminant limits are binding.", "",
             "| ID | Parameter | Limit | Applies to | Source | Note |",
             "| --- | --- | ---: | --- | --- | --- |"]
    for row in standards:
        lines.append(
            "| {id} | {parameter} | {limit} {unit} | {scope} | {source} | {notes} |".format(
                id=row["id"],
                parameter=row["parameter"],
                limit=fmt_number(float(row["limit_value"]), 2),
                unit=row["unit"],
                scope=row["applies_to"],
                source=row["source_id"].replace(";", ", "),
                notes=row["notes"],
            )
        )
    lines.append("")
    return "\n".join(lines)


def render_surveys(surveys: list[dict[str, str]]) -> str:
    lines = [GENERATED_NOTE, "# Market quality surveys", "",
             "Independent and industry testing of retail omega-3 products. Results are",
             "not directly comparable across studies because sampling frames, assays and",
             "product mixes differ; the pattern matters more than any single number.", "",
             "| ID | Study | Market | Year | N | Parameter | Result | Note |",
             "| --- | --- | --- | --- | ---: | --- | ---: | --- |"]
    for row in surveys:
        lines.append(
            "| {id} | {study} | {market} | {year} | {n} | {parameter} | {result}{unit} | {notes} |".format(
                id=row["id"],
                study=row["study"],
                market=row["market"],
                year=row["year_sampled"],
                n=row["n_products"],
                parameter=row["parameter"],
                result=fmt_number(float(row["result"]), 1),
                unit="%" if row["unit"] == "percent" else f" {row['unit']}",
                notes=row["notes"].replace("|", "\\|"),
            )
        )
    lines.append("")
    return "\n".join(lines)


def render_references(references: list[dict[str, str]]) -> str:
    lines = [GENERATED_NOTE, "# References", "",
             f"{len(references)} sources. DOIs are given where verified; otherwise a",
             "stable URL or PMID is supplied. Citations with descriptive titles indicate",
             "that the exact published title could not be confirmed character-for-character.",
             "",
             "| ID | Citation | Identifier |", "| --- | --- | --- |"]
    for row in sorted(references, key=lambda item: item["id"]):
        if row["doi"]:
            identifier = f"[doi:{row['doi']}](https://doi.org/{row['doi']})"
        elif row["pmid"]:
            identifier = f"[PMID {row['pmid']}](https://pubmed.ncbi.nlm.nih.gov/{row['pmid']}/)"
        else:
            identifier = f"[link]({row['url']})"
        lines.append(f"| {row['id']} | {row['citation'].replace('|', chr(92) + '|')} | {identifier} |")
    lines.append("")
    return "\n".join(lines)


# --------------------------------------------------------------------------- #
# Link checking
# --------------------------------------------------------------------------- #

LINK_RE = re.compile(r"\[[^\]]*\]\(([^)]+)\)")


def check_links() -> list[str]:
    problems: list[str] = []
    seen: set[str] = set()
    targets = [ROOT / "README.md", *DOCS.rglob("*.md"), *(ROOT / "report").glob("*.md")]
    for path in targets:
        if not path.exists():
            continue
        text = path.read_text(encoding="utf-8")
        for target in LINK_RE.findall(text):
            target = target.split("#", 1)[0].strip()
            if not target or target.startswith(("http://", "https://", "mailto:")):
                continue
            resolved = (path.parent / target).resolve()
            if not resolved.exists():
                key = f"{path.relative_to(ROOT)}: broken link -> {target}"
                if key not in seen:
                    seen.add(key)
                    problems.append(key)
    return problems


