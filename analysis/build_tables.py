def build() -> dict[Path, str]:
    data = validate()
    if errors:
        return {}
    return {
        GENERATED / "brand-comparison.md": render_brand_table(data["products"]),
        GENERATED / "evidence-tables.md": render_evidence(data["evidence"]),
        GENERATED / "claims-table.md": render_claims(data["claims"]),
        GENERATED / "dosing-table.md": render_dosing(data["dosing"]),
        GENERATED / "quality-standards.md": render_standards(data["standards"]),
        GENERATED / "quality-surveys.md": render_surveys(data["surveys"]),
        DOCS / "references.md": render_references(data["references"]),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    outputs = build()
    if errors:
        print("VALIDATION FAILED", file=sys.stderr)
        for message in errors:
            print(f"  - {message}", file=sys.stderr)
        return 1

    stale: list[str] = []
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if args.check:
            existing = path.read_text(encoding="utf-8") if path.exists() else ""
            if existing != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8")

    if args.check:
        if stale:
            print("STALE GENERATED FILES:", file=sys.stderr)
            for name in stale:
                print(f"  - {name}", file=sys.stderr)
            print("Run: python analysis/build_tables.py", file=sys.stderr)
            return 1
        broken = check_links()
        if broken:
            print("BROKEN LINKS:", file=sys.stderr)
            for problem in broken:
                print(f"  - {problem}", file=sys.stderr)
            return 1
        print(f"OK: {len(outputs)} generated files current, all relative links resolve")
        return 0

    print(f"Regenerated {len(outputs)} files:")
    for path in outputs:
        print(f"  - {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
